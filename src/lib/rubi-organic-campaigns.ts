/** RUBI 11× organic campaign labels. These are marketing labels, not payment attribution. */
export const RUBI_ORGANIC_CHANNELS = [
  { id: "instagram", label: "Instagram" },
  { id: "tiktok", label: "TikTok" },
  { id: "youtube", label: "YouTube Shorts" },
  { id: "facebook", label: "Facebook" },
  { id: "pinterest", label: "Pinterest" },
  { id: "whatsapp", label: "WhatsApp" },
  { id: "telegram", label: "Telegram" },
] as const;

export type RubiOrganicChannel = typeof RUBI_ORGANIC_CHANNELS[number]["id"];
const allowedChannels = new Set<string>(RUBI_ORGANIC_CHANNELS.map(channel => channel.id));
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const CAMPAIGN = /^[a-z0-9][a-z0-9_-]{0,59}$/;

export function normalizeRubiCampaign(value: string): string {
  const clean = value.trim().toLowerCase()
    .normalize("NFKD").replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9_-]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^[-_]+|[-_]+$/g, "")
    .slice(0, 60).replace(/[-_]+$/g, "");
  return CAMPAIGN.test(clean) ? clean : "";
}

export function rubiOrganicProductPath(productId: string, channel: RubiOrganicChannel, campaign: string): string {
  if (!UUID.test(productId)) throw new Error("Produto inválido.");
  if (!allowedChannels.has(channel)) throw new Error("Canal de divulgação inválido.");
  const slug = normalizeRubiCampaign(campaign);
  if (!slug) throw new Error("Informe o nome da campanha.");
  const params = new URLSearchParams({ utm_source: channel, utm_medium: "organic_social", utm_campaign: slug });
  return `/hub-product/${productId}?${params.toString()}`;
}

export type RubiOrganicAttribution = { source: RubiOrganicChannel; campaign: string };

/** Accept only labels generated by RUBI; never accept a payment/referral ID from a UTM. */
export function readRubiOrganicAttribution(query: string): RubiOrganicAttribution | null {
  const params = new URLSearchParams(query.startsWith("?") ? query.slice(1) : query);
  if (params.get("utm_medium") !== "organic_social") return null;
  const source = params.get("utm_source")?.toLowerCase() ?? "";
  if (!allowedChannels.has(source)) return null;
  const campaign = params.get("utm_campaign") ?? "";
  if (!CAMPAIGN.test(campaign)) return null;
  return { source: source as RubiOrganicChannel, campaign };
}

/**
 * Keep a per-product or per-partner-link label for one browser tab only,
 * so a newly registered visitor returning to the product retains the
 * *marketing* campaign. Never treat this as affiliate attribution.
 */
export function currentRubiOrganicAttribution(journeyKey: string): RubiOrganicAttribution | null {
  if (typeof window === "undefined" || !UUID.test(journeyKey)) return null;
  const key = `rubi_organic_journey_${journeyKey}`;
  const current = readRubiOrganicAttribution(window.location.search);
  try {
    if (current) {
      window.sessionStorage.setItem(key, JSON.stringify(current));
      return current;
    }
    const stored = window.sessionStorage.getItem(key);
    if (!stored) return null;
    const parsed: unknown = JSON.parse(stored);
    if (!parsed || typeof parsed !== "object") return null;
    const context = parsed as Record<string, unknown>;
    if (typeof context.source !== "string" || typeof context.campaign !== "string") return null;
    return readRubiOrganicAttribution(new URLSearchParams({
      utm_medium: "organic_social",
      utm_source: context.source,
      utm_campaign: context.campaign,
    }).toString());
  } catch {
    // Private mode can block session storage. Tracking remains optional.
    return current;
  }
}
